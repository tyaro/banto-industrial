/**
 * 2026-09-01 オーナー要望「タグ登録で、タグ名が空欄のままならアドレスを
 * タグ名として使う」: `tags/+page.svelte` の単票登録**新規作成**フォーム
 * （create Drawer）だけが使う、依存ゼロの純関数。`tagFormCarry.ts`/
 * `tagDuplicate.ts` と同じ方針 - ページ側の `FormState` を直接 import せず、
 * プリミティブ値だけを受け取ってテストしやすく保つ。
 *
 * 対象を単票登録の新規作成フォームに絞った理由（実装指示どおり）:
 * - **連続登録は対象外**: `continuousRegistration.ts::generateContinuousTags`
 *   が独自の命名規則（連番+開始アドレスからの自動生成）を持ち、意味論が
 *   別。
 * - **CSV 取込は対象外**: `tagCsv.ts` の取込形式は名前列を明示的に持つため、
 *   空欄の扱いを変えると取込の意味論が変わる。
 * - **編集フォームは対象外**: 既存タグの名前欄を空にする操作は「消したい」
 *   （＝空文字列で更新したい）意図かもしれず、勝手にアドレスで埋めるべき
 *   ではない。
 *
 * 実装方針（実装指示「保存時に黙って置き換えるのではなく、フォーム上で
 * 見える形にすること」）: `toInput`（送信直前の変換）で名前が空ならアドレス
 * を埋める、という「保存時の置換」にはしなかった。理由は2つ:
 * 1. ユーザーが保存前に「実際に何が登録されるか」を名前欄そのもので
 *    確認・上書きできない（送信ボタンを押すまで結果が見えない）のは、
 *    アドレス直値をタグ名に使う運用（産業用途で実際に多い）にしては不親切。
 * 2. 名前欄が空のままだと `<input required>` の HTML5 制約検証に引っかかり
 *    送信できない（`banto-hub-tags-form.spec.ts` の「名前を空のまま送信すると
 *    HTML5 validation で止まる」テストが保証している既存の安全策）。
 *    保存時にしか埋めないと、この安全策とタイミングが噛み合わず送信できない
 *    まま名前欄が空に見え続けてしまう。
 *
 * そのためフォーム側（`+page.svelte`）でアドレス欄の `oninput` の都度この
 * 関数を呼び、名前欄をその場でプリフィルする。ConnectionDrawer.svelte の
 * `portTouched`（`plcConnectionForm.ts` のプロトコル別既定ポート追従）と
 * 同じ「touched 追跡」方式を踏襲する: 名前欄をユーザーが一度でも直接編集
 * したら `nameTouched` を立て、以後はアドレスが変わっても追従させない
 * （「ユーザーが名前欄を自分で編集した後は、勝手に上書きしないこと」）。
 * `nameTouched` が立っていない間は、現在の名前の中身に関わらず常に新しい
 * アドレスをそのまま返す - これにより「名前が空 → プリフィル」だけでなく
 * 「名前が前のアドレスのまま（＝プリフィル由来で未編集）→ アドレス変更に
 * 追従」も同じ1本のロジックで満たす（`portTouched` が現在のポート値と
 * 既定値を比較せず、フラグ1つだけで追従の可否を判定しているのと同じ設計）。
 */

/**
 * アドレス欄の `oninput` から呼ぶ。名前欄へ次に設定すべき値を返す -
 * プリフィルすべきでない場合は `null` を返すので、呼び出し側は
 * `if (next !== null) form.name = next;` の形でだけ使えばよい
 * （`null` の間は名前欄に一切触れない）。
 *
 * - `isPlc` が `false`（`tagKind` が `computed`/`internal` 等）なら常に
 *   `null`。PLC タグ以外はアドレス欄自体を持たないため対象外
 *   （実装指示「`form.tagKind === 'plc'` のときだけ働かせること」）。
 * - `nameTouched` が `true`（名前欄をユーザーが既に直接編集済み、または
 *   複製フォームのように既に意味のある名前が入っている）なら `null`。
 * - どちらでもなければ `newAddress` をそのまま返す（空文字列に戻す入力も
 *   含めて素直に追従する - 「アドレスを消したらプリフィルも消える」が
 *   自然な挙動のため、`newAddress` に対する特別扱いはしない）。
 */
export function nextTagNameOnAddressChange(
	isPlc: boolean,
	newAddress: string,
	nameTouched: boolean
): string | null {
	if (!isPlc || nameTouched) return null;
	return newAddress;
}
